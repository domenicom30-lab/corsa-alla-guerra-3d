import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {grenadeThreat,grenadeThreatPoint,drawGrenadeThreat} from '../grenade-threat.js';
const H=500,ground=390;
const t=grenadeThreat(400,ground,H,-1);
assert.ok(t&&t.flightTime>1&&t.flightTime<2);
assert.ok(t.landingX<400,'Warning must land in the enemy facing direction');
assert.equal(t.landingY,ground-H*.03);
const first=grenadeThreatPoint(t,0),middle=grenadeThreatPoint(t,.5),last=grenadeThreatPoint(t,1);
assert.equal(first.x,t.x);
assert.ok(middle.y<first.y,'Grenade rises before falling');
assert.ok(Math.abs(last.y-t.landingY)<1e-7,'Marker must match projectile physics');
assert.ok(Math.abs(last.x-t.landingX)<1e-7);
assert.equal(grenadeThreat(NaN,ground,H,1),null);
assert.equal(grenadeThreat(0,ground,-50,1),null);
assert.ok(grenadeThreat(400,ground,H,1).landingX>400);
let calls={save:0,restore:0,rect:0,arc:0,stroke:0};
const noop=()=>{};
const ctx={save(){calls.save++},restore(){calls.restore++},fillRect(){calls.rect++},
 stroke(){calls.stroke++},beginPath:noop,ellipse(){calls.arc++}};
assert.equal(drawGrenadeThreat(ctx,t,H,.45,9,1000),true);
assert.equal(calls.save,1);assert.equal(calls.restore,1);
assert.ok(calls.rect>8,'A visible but bounded path must be drawn');
assert.ok(calls.arc===1,'A clear impact circle shows the landing location');
const originalCalls={...calls};
assert.equal(drawGrenadeThreat(ctx,t,H,0,9,1000),false);
assert.deepEqual(calls,originalCalls,'No overlay after an attack has fired');
const src=readFileSync('main.js','utf8');
const director=readFileSync('enemy-director.js','utf8');
assert.ok(src.includes("grenadeThreat(x,ground(),H,facingPlayer)"));
assert.ok(src.includes("drawGrenadeThreat(ctx,threat,H,e.windup,phase,W)"));
assert.ok(director.includes("vx:dir*H*.5,vy:-H*.78,gravity:H*1.55"),'Warning must match actual grenade trajectory');
const workflow=readFileSync('.github/workflows/build-apk.yml','utf8');
assert.ok(workflow.includes("on:\n  workflow_dispatch:"));
assert.ok(!workflow.includes("\n  push:"));
console.log('PASS: timed ballistic grenade danger arc, accurate landing marker, no permanent overlay and no APK triggers');
