import assert from 'node:assert/strict';
import {createArcadeSystems} from '../arcade-mechanics.js';
const a=createArcadeSystems();
assert.equal(a.weapon,'normal');
assert.equal(a.grenadeCount,8);
const shots=a.fire(100,100,1,600);
assert.equal(shots.length,1);
assert.equal(shots[0].vx,600);
assert.equal(a.throwGrenade(100,100,1,500),true);
assert.equal(a.grenadeCount,7);
let explosions=0;
for(let i=0;i<70;i++)a.step(.02,0,100,400,500,()=>{},()=>explosions++);
assert.equal(explosions,1,'Grenade must explode once');
a.reset();
assert.equal(a.grenadeCount,8);
assert.equal(a.grenades.length,0);
assert.equal(a.kill(),120);
assert.equal(a.kill(),140);
a.reset();
assert.equal(a.combo,0);
const p=a.pickups.find(p=>p.type==='spread');
assert.equal(a.collect(p.x,0,400,500),'spread');
assert.equal(a.weapon,'spread');
assert.equal(a.fire(100,100,1,600).length,3);
assert.equal(a.ammo,99);
a.reset();
const heavy=a.pickups.find(p=>p.type==='heavy');
assert.equal(a.collect(heavy.x,0,400,500),'heavy');
assert.equal(a.fire(100,100,-1,600)[0].damage,2);
a.reset();
a.step(.02,8500,1000,400,500,()=>{},()=>{});
assert.equal(a.boss.active,true);
assert.equal(a.boss.hp,28);
a.reset();
assert.equal(a.throwGrenade(100,100,1,500),true);
a.step(.01,25,100,400,500,()=>{},()=>{},25);
assert.ok(a.grenades[0].x<100,'Grenade must shift with camera');
a.reset();
assert.equal(typeof a.draw,'function','Boss and pickup renderer must exist');

a.reset();
a.step(.02,8500,1000,400,500,()=>{},()=>{});
for(let i=0;i<150;i++)a.step(1.2,0,100,400,500,()=>{},()=>{});
assert.equal(a.enemyShots.length,0,'Offscreen boss must not spawn projectiles');
a.reset();
a.step(.02,8500,1000,400,500,()=>{},()=>{});
for(let i=0;i<150;i++)a.step(1.2,8500,1000,400,500,()=>{},()=>{});
assert.ok(a.enemyShots.length<=24,'Boss projectiles must stay bounded');
a.reset();
assert.equal(a.hitCover(2350,350,400,500,50),true,'Cover should absorb incoming shots');
assert.equal(a.covers[0].hp,50);
assert.equal(a.hitCover(2350,350,400,500,50),true);
assert.equal(a.covers[0].hp,0,'Cover should be destroyed');
assert.equal(a.hitCover(2350,350,400,500,10),false,'Destroyed cover should no longer block');
a.reset();
assert.equal(a.covers[0].hp,100,'Reset should restore cover');
assert.equal(a.rescue(1750,0,500),1,'Prisoner should be rescuable');
assert.equal(a.rescue(1750,0,500),0,'Rescue should only count once');
a.reset();
assert.equal(a.rescue(1750,0,500),1,'Reset should restore prisoner');
console.log('PASS: arcade combat, grenades, pickups, weapons, combo, reset and boss');
