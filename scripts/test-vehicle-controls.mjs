import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {vehicleInteraction} from '../vehicle-controls.js';
import {heroDimensions,troopDimensions,vehicleDimensions,activeBodyRatio} from '../arcade-proportions.js';
const H=850,position=1100;
const state=(changes={})=>vehicleInteraction({running:true,paused:false,occupied:false,hp:100,vehicleX:position,playerX:500,H,...changes});
assert.deepEqual(state({running:false}),{visible:false,disabled:true,action:'none',label:'CARRO'});
assert.equal(state({paused:true}).action,'none');
assert.equal(state({hp:0}).visible,false);
assert.equal(state().action,'approach');
assert.equal(state().disabled,true,'Do not allow entering distant vehicle');
assert.equal(state({playerX:position-H*.24}).action,'enter');
assert.equal(state({playerX:position-H*.24}).disabled,false);
assert.equal(state({playerX:position+H*.24}).action,'enter');
assert.equal(state({playerX:position-H*.241}).action,'approach','Interaction stops strictly outside range');
assert.equal(state({occupied:true,playerX:0}).action,'exit','Allow exit without distance after vehicle follows the player');
assert.equal(state({occupied:true,playerX:0}).disabled,false);
assert.equal(state({playerX:position+H*1.1}).visible,false);
for(const invalidH of [0,-9])assert.equal(state({H:invalidH,playerX:0}).action,'none');
const hero=heroDimensions(H),rifle=troopDimensions(H),heavy=troopDimensions(H,'heavy'),tank=vehicleDimensions(H),boss=vehicleDimensions(H,true);
const fraction=activeBodyRatio();
assert.ok(hero.h*fraction/H>=.15&&hero.h*fraction/H<=.175);
assert.ok(rifle.h*fraction/H>=.15&&rifle.h*fraction/H<=.17);
assert.ok(heavy.h*fraction/H>=.17&&heavy.h*fraction/H<=.20);
assert.ok(tank.h*34/19/H>=.24&&tank.h*34/19/H<=.28);
assert.ok(boss.h/H<.42);
const html=readFileSync('index.html','utf8'),main=readFileSync('main.js','utf8'),css=readFileSync('style.css','utf8'),mechanics=readFileSync('arcade-mechanics.js','utf8');
const version=JSON.parse(readFileSync('package.json','utf8')).version.split('.').slice(0,2).join('.');
for(const text of ['id="vehicle-toggle"','ENTRA NEL CARRO','2D · v'+version])assert.ok(html.includes(text),text);
for(const text of ["import {vehicleInteraction} from './vehicle-controls.js'",'function currentVehicleInteraction()', 'function updateVehicleButton()',"document.getElementById('vehicle-toggle')",'updateVehicleButton();',"if(action!=='enter'&&action!=='exit')return"])assert.ok(main.includes(text),text);
assert.ok(!main.includes("document.createElement('button');rideButton.id='vehicle-toggle'"),'Remove floating car button');
assert.ok(css.includes('#vehicle-toggle[hidden]{display:none!important}'));
assert.ok(css.includes('#vehicle-toggle:disabled'));
assert.ok(mechanics.includes('const playerCenterY=ground-H*(crouching?.060:.092)-jumping;'));
assert.ok(mechanics.includes('const verticalRadius=H*(crouching?.055:.082);'));
console.log('PASS: compact soldier/tank scale, accurate projectile hitbox and conditional mobile ENTER/EXIT button');
