import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import {arcadeArt,drawArcadeSoldierFrame} from '../arcade-art.js';
const main=readFileSync('main.js','utf8'),html=readFileSync('index.html','utf8');
const art=readFileSync('arcade-art.js','utf8'),enemies=readFileSync('enemy-frames.js','utf8');
const stage=readFileSync('arcade-cinematics.js','utf8');
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.ok(html.includes('src="./main.js"'),'2D game must start directly');
assert.ok(!existsSync('bootstrap.js')&&!existsSync('three-game.js'),'3D runtime removed');
assert.ok(!existsSync('public/models/Soldier.glb'),'3D models removed');
assert.ok(!pkg.dependencies.three,'Three.js dependency removed');
assert.ok(main.includes('drawArcadeSoldierFrame(ctx,pose,frame'),'Real sprite animations connected');
assert.ok(main.includes('drawSentries();'),'Riflemen rendered');
assert.ok(main.includes('arcade.enemyShots.push('),'Riflemen attack');
assert.ok(main.includes('paintArcadeBackground(ctx,W,H,scroll)'),'Backdrop draws');
assert.ok(art.includes("crate:'../2d/crate.png'")&&art.includes("sandbags:'../2d/sandbags.png'"),'User-supplied assets used');
assert.ok(existsSync('corsa-alla-guerra-2d-assets-1.zip'),'Original 2D pack retained');
assert.ok(existsSync('corsa-alla-guerra-reference-2d.zip'),'Reference pack retained');
assert.ok(enemies.includes('prepareSentryFrames')&&enemies.includes('drawSentryFrame'),'Sentry animations exist');
assert.ok(stage.includes('drawWarzoneParallax'),'Layered 2D stage exists');
const captured=[],ctx={imageSmoothingEnabled:true,drawImage(...args){captured.push(args)}};
arcadeArt.soldier_run={naturalWidth:576,naturalHeight:112};
assert.equal(drawArcadeSoldierFrame(ctx,'run',7,10,20,80,100),true);
assert.deepEqual(captured[0].slice(1,5),[504,0,72,112]);
arcadeArt.soldier_fire={naturalWidth:288,naturalHeight:112};
assert.equal(drawArcadeSoldierFrame(ctx,'fire',3,0,0,80,100),true);
assert.deepEqual(captured[1].slice(1,5),[216,0,72,112]);
assert.equal(drawArcadeSoldierFrame(ctx,'jump',0,0,0,80,100),false);
console.log('PASS: true 2D mode, original raster packs, animated sprite sheets and enemies');
