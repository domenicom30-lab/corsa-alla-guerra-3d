import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const boot=readFileSync('bootstrap.js','utf8');
const game=readFileSync('three-game.js','utf8');
const html=readFileSync('index.html','utf8');
assert.ok(html.includes('src="./bootstrap.js"'),'The production entrypoint must load the mode selector');
assert.ok(boot.includes("import('./three-game.js')"),'3D mode must actually load');
assert.ok(boot.includes("import('./main.js')"),'Existing 2D arcade must remain available');
assert.ok(boot.includes("p.get('mode')==='2d'?'2d':'3d'"),'Default mode must be real 3D');
assert.ok(game.includes('new THREE.WebGLRenderer'),'3D mode must use WebGL');
assert.ok(game.includes('new GLTFLoader().load(soldierPaths[index]'),'Soldier GLB must be loaded into scene');
assert.ok(game.includes('playerRoot.remove(playerVisual);playerVisual=model;playerRoot.add(playerVisual)'),'GLB must replace placeholder at runtime');
assert.ok(game.includes("'/models/ww2_panzergrenadier_2k_cc0-optimized.glb'"),'User-provided model must be preferred');
assert.ok(existsSync('public/models/ww2_panzergrenadier_2k_cc0-optimized.glb'),'The shipped GLB must exist');
assert.ok(game.includes("bindButton('shoot','shoot',fire)"),'Touch fire must be connected');
assert.ok(game.includes("bindButton('left','left')"),'Touch movement must be connected');
assert.ok(game.includes('function enterTank()'),'Drivable tank must be implemented');
assert.ok(game.includes('bossHp=Math.max(0,bossHp-b.damage)'),'Boss should be killable');
assert.ok(game.includes("if(distance>=200&&bossHp===0)"),'Finish requires boss defeat');
console.log('PASS: 3D engine, supplied model, forest, vehicles, controls and 2D compatibility');
